def _loop(monkeypatch, orchestrator: dict, *, good: bool | None = None,
          idea_status: str = "refuted", fresh: bool = True):
    """run_loop from protocol_execution (fresh=True) or from wherever the state
    stands (fresh=False, e.g. a resume). The backtest itself is stubbed: its
    artifacts are pre-seeded. Returns (run_dir, stages, reader_calls)."""
    _set_orchestrator(orchestrator)
    if fresh:
        run_dir = _minimal_run_at(rpr.ROOT, RUN_ID, "protocol_execution")
        _seed(pending="protocol_execution", idea_status=idea_status)
        rpr._ensure_protocol_ref_pinned(run_dir, RUN_ID,
                                        {"protocol_ref": f"protocols/{RUN_ID}_pinned.json"})
        rpr.save_yaml(run_dir / "handoffs" / "backtest_spec_to_protocol_execution.yaml",
                      {"required_inputs": [], "deliverables": []})
        if good is not None:
            rpr.save_yaml(run_dir / "artifacts" / "protocol_result.yaml",
                          _pr("single", run_dir / "results", good))
            _seed_dsr_ledger()
        for c in REPORT_CATEGORIES:
            (run_dir / "artifacts" / "proposals" / f"{c}.yaml").unlink()
    else:
        run_dir = rpr.ROOT / "runs" / RUN_ID
    stages, calls = [], []

    async def _record(stage_name, run_id, retry_context=None):
        stages.append(stage_name)
    monkeypatch.setattr(rpr, "async_invoke_agent", _record)
    monkeypatch.setattr(rpr, "_invoke_reader_llm", _fake_llm(calls=calls))
    rpr.run_loop(RUN_ID)
    return run_dir, stages, calls


