def _variant_run(graded: dict, idea_status: str = "refuted", stale: dict | None = None) -> Path:
    """Variant loop on. `graded` = {variant_id: good?} are this attempt's grid
    columns; `broken` is validated but has no column (its backtest failed this
    attempt) -- `stale` may still leave an old protocol_result on disk for it;
    `asset` was not tested by the data gate."""
    run_dir = _seed(idea_status="refuted", variant_loop=True)
    arts = run_dir / "artifacts"
    index = {vid: {"status": "validated",
                   "config_path": f"artifacts/variants/{vid}/strategy_config.json"}
             for vid in list(graded) + ["broken"]}
    index["asset"] = {"status": "not_tested", "reason": "patch application failed: /x"}
    rpr.save_yaml(arts / "variants" / "index.yaml", {"variants": index})
    for vid, good in graded.items():
        rpr.save_yaml(arts / "variants" / vid / "protocol_result.yaml",
                      _pr(vid, run_dir / "variants" / vid / "results", good))
    broken = arts / "variants" / "broken" / "protocol_result.yaml"
    if stale:
        rpr.save_yaml(broken, _pr("broken", run_dir / "variants" / "broken" / "results",
                                  stale["good"]))
    elif broken.exists():
        broken.unlink()
    grid = _grid(list(graded), idea_status)
    rpr.save_yaml(arts / "grid_evaluation.yaml", grid)
    rpr.save_yaml(arts / "idea_status.yaml", rpr._build_idea_status_artifact(grid, RUN_ID))
    rows = [{"trial_id": f"{RUN_ID}:{vid}", "source": "backtest", "sharpe": 0.3,
             "forecast_hash": f"fh-{vid}"} for vid in graded]
    rows.append({"trial_id": f"{RUN_ID}:broken", "source": "backtest_failed", "sharpe": None,
                 "forecast_hash": "fh-broken"})
    rpr.save_yaml(rpr.CAMPAIGN_STATE_PATH, {"campaign_id": "t", "runs": [], "trial_sharpes": rows})
    _seed_dsr_ledger()
    return run_dir


