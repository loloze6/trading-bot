def _write_equity(results_root: Path, window_run_id: str, closes: list,
                  warmup_rows: int = 2, bars_per_day: int = 2) -> None:
    """portfolio_states.csv for one window: `warmup_rows` NOT_READY rows, then
    `bars_per_day` bars per day whose LAST bar carries that day's close. The
    earlier bars carry the midpoint of the previous close and this close: a
    realistic intraday path (no dip below both closes, so it adds no bar-level
    drawdown), but a daily return taken from them would differ from the one
    taken from the last bar, so the last-bar rule is still exercised."""
    d = results_root / window_run_id
    d.mkdir(parents=True, exist_ok=True)
    lines = ["timestamp,regime,postRebalance_total_value,total_portfolio_value"]
    for i in range(warmup_rows):
        lines.append(f"2020-01-01 0{i}:00:00,NOT_READY,999999.0,999999.0")
    for day, close in enumerate(closes):
        date = f"2020-01-{day + 2:02d}"
        mid = (closes[max(day - 1, 0)] + close) / 2
        for b in range(bars_per_day - 1):
            lines.append(f"{date} {b:02d}:00:00,trend,{mid},{mid}")
        lines.append(f"{date} 23:00:00, trend ,{close},{close}")
    (d / "portfolio_states.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _pr(tag: str, results_root: Path, good: bool) -> dict:
    """A protocol_result with 2 symbols x 2 windows, each window backed by an
    equity file. good=True clears every bar (DSR against _seed_dsr_ledger);
    good=False fails them."""
    results = []
    for sym in ("BTCUSDT", "ETHUSDT"):
        for w in ("w1", "w2"):
            wid = f"{tag}-{sym}-{w}"
            growth = 1.002 if good else 0.995
            _write_equity(results_root, wid, [1000.0 * growth ** k for k in range(8)])
            results.append({"symbol": sym, "window": w, "run_id": wid,
                            "core": {"sharpe": 1.4 if good else -1.0}})
    pss = ({"BTCUSDT": {"median_sharpe": 1.5, "max_abs_drawdown_pct": 10.0, "min_trade_count": 50},
            "ETHUSDT": {"median_sharpe": 1.3, "max_abs_drawdown_pct": 12.0, "min_trade_count": 60}}
           if good else
           {"BTCUSDT": {"median_sharpe": -1.0, "max_abs_drawdown_pct": 40.0, "min_trade_count": 3},
            "ETHUSDT": {"median_sharpe": -0.5, "max_abs_drawdown_pct": 30.0, "min_trade_count": 5}})
    return {"verdict": "promote" if good else "kill", "results": results,
            "per_symbol_summary": pss,
            "protocol_file": str(rpr.ROOT / "protocols" / "p.json")}


def _seed_dsr_ledger() -> None:
    """Append 10 real-Sharpe trial rows from other runs so the DSR is computable:
    trial Sharpes spread around 0, so a candidate at ~1.4 deflates to ~1.0."""
